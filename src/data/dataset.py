"""Audio-Visual dataset with on-the-fly mix-and-separation.

SPEC 11.2, 7.1: Synthetic mixtures from clean (source, video) pairs.
"""
import json
import os
import random
from typing import Any, Dict, List, Optional, Tuple

import torch
from torch.utils.data import Dataset, DataLoader
import torch.nn.functional as F

from src.data.preprocessing import (
    AudioPreprocessor,
    STFTModule,
    get_temporal_alignment_table,
    N_VIDEO_FRAMES,
    CLIP_LENGTH,
)


# --------------------------------------------------------------------------- #
# New dataset: reads cached cRM / DINOv2 features, does on-the-fly mixing
# --------------------------------------------------------------------------- #
class MixAndSepareDataset(Dataset):
    """Mix-and-separate dataset with cached cRM and DINOv2 features.

    Reads the ``index.json`` produced by ``scripts/preprocess_data.py``
    and performs on-the-fly mixing of *N* distinct clips.

    Parameters
    ----------
    index_file :
        Path to ``index.json`` generated by the preprocessing script.
    n_sources :
        Number of sources to mix per training sample.
    split :
        Which split to use: ``"train"``, ``"val"``, or ``"test"``.  Only
        clips whose ``"split"`` field matches are used.
    cache_dir :
        Root directory containing ``crm/``, ``visual/``, etc.  If ``None``,
        the directory containing *index_file* is used.
    include_visual :
        Whether to load DINOv2 visual features (``False`` for Phase 1).
    device :
        Torch device on which to place loaded tensors.
    """

    def __init__(
        self,
        index_file: str,
        n_sources: int = 2,
        split: str = "train",
        cache_dir: Optional[str] = None,
        include_visual: bool = True,
        device: str = "cpu",
    ):
        super().__init__()
        self.index_file = index_file
        self.n_sources = n_sources
        self.split = split
        self.include_visual = include_visual
        self.device = torch.device(device)

        with open(index_file, "r") as f:
            self._all_meta = json.load(f)

        self.clips = [
            cid for cid, meta in self._all_meta.items()
            if meta.get("split", "train") == split
        ]
        if not self.clips:
            raise ValueError(f"No clips found for split '{split}'")

        self.cache_dir = cache_dir or os.path.dirname(index_file)
        self._stft = STFTModule()

    # ------------------------------------------------------------------ #
    # Helpers
    # ------------------------------------------------------------------ #

    @staticmethod
    def _load_waveform(path: str) -> torch.Tensor:
        """Load waveform and enforce [L] float32."""
        if path.endswith(".pt"):
            wave = torch.load(path, weights_only=False)
        else:
            import torchaudio
            waveform, sr = torchaudio.load(path)
            ap = AudioPreprocessor()
            wave = ap(waveform, sr)
        if wave.dim() == 2:
            wave = wave.squeeze(0)
        return wave.float()

    @staticmethod
    def _pad_waveforms(waves: List[torch.Tensor]) -> List[torch.Tensor]:
        max_len = max(w.shape[-1] for w in waves)
        out = []
        for w in waves:
            if w.shape[-1] < max_len:
                w = F.pad(w, (0, max_len - w.shape[-1]))
            out.append(w)
        return out

    @staticmethod
    def _mix(waves: List[torch.Tensor],
             db_range: Tuple[float, float] = (-5.0, 5.0)
             ) -> Tuple[torch.Tensor, torch.Tensor]:
        """Mix waveforms with random dB gains."""
        stacked = torch.stack(waves)  # [N, L]
        n = stacked.shape[0]
        db = torch.rand(n) * (db_range[1] - db_range[0]) + db_range[0]
        gains = 10 ** (db / 20.0)
        scaled = stacked * gains.unsqueeze(1)
        mixture = scaled.sum(dim=0)  # [L]
        return mixture, gains

    # ------------------------------------------------------------------ #
    # Dataset protocol
    # ------------------------------------------------------------------ #

    def __len__(self) -> int:
        return len(self.clips)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        if len(self.clips) < self.n_sources:
            raise ValueError(
                f"Not enough clips ({len(self.clips)}) for n_sources={self.n_sources}"
            )
        clip_ids = random.sample(self.clips, self.n_sources)

        # Load waveforms per source
        source_waves = []
        for clip_id in clip_ids:
            meta = self._all_meta[clip_id]
            spaths = meta.get("source_paths", [])
            if not spaths:
                raise RuntimeError(f"No source_paths for clip {clip_id}")
            wave = self._load_waveform(spaths[0])
            source_waves.append(wave)

        # Pad, mix, compute STFT
        source_waves = self._pad_waveforms(source_waves)
        mixture_wave, source_gains = self._mix(source_waves)
        # STFTModule enforces length=96000; pad/truncate mixture to match
        if mixture_wave.shape[-1] != CLIP_LENGTH:
            if mixture_wave.shape[-1] < CLIP_LENGTH:
                mixture_wave = F.pad(mixture_wave, (0, CLIP_LENGTH - mixture_wave.shape[-1]))
            else:
                mixture_wave = mixture_wave[:CLIP_LENGTH]
        mixture_stft = self._stft(mixture_wave)  # [2, F, T]
        target_waveforms = torch.stack(source_waves)  # [N, L]

        output: Dict[str, Any] = {
            "mixture_stft": mixture_stft,
            "target_waveforms": target_waveforms,
            "source_gains": source_gains,
        }

        # Visual features
        if self.include_visual:
            visual_list = []
            for clip_id in clip_ids:
                vpath = self._all_meta[clip_id].get("visual_path")
                if vpath and os.path.exists(vpath):
                    vf = torch.load(vpath, weights_only=False)
                    visual_list.append(vf)
            if visual_list:
                # Resample to same frame count (N_VIDEO_FRAMES=150) instead of slicing
                target_frames = N_VIDEO_FRAMES
                aligned = []
                for v in visual_list:
                    # v: [V, 1024, 768] -> interpolate time dimension
                    v = v.permute(1, 2, 0).unsqueeze(0)  # [1, 1024, 768, V]
                    v = F.interpolate(v, size=target_frames, mode='linear', align_corners=False)
                    v = v.squeeze(0).permute(2, 1, 0)  # [V, 1024, 768]
                    aligned.append(v)
                stacked = torch.stack(aligned)  # [N, V, 1024, 768]
                output["video_frames"] = stacked.mean(dim=0)  # [V, 1024, 768]

        # CRM targets - load in same clip_ids order to match mixed sources
        all_crms = []
        for clip_id in clip_ids:
            cpath = self._all_meta[clip_id].get("crm_path")
            if cpath and os.path.exists(cpath):
                crm = torch.load(cpath, weights_only=False)
                # crm shape: [n_src, 2, F, T]; take first source (index 0) per clip
                all_crms.append(crm[0:1])  # [1, 2, F, T]
        if len(all_crms) == self.n_sources:
            output["target_crm_masks"] = torch.cat(all_crms, dim=0)  # [N, 2, F, T]

        return output


