class AudioVisualDataset(Dataset):
    """Dataset for training. Samples N clean sources, mixes them."""

    def __init__(
        self,
        index_file: str,
        n_sources: int = 2,
        split: str = "train",
        include_visual: bool = True,
    ):
        self.index_file = index_file
        self.n_sources = n_sources
        self.include_visual = include_visual
        self.stft = STFTModule()
        self.alignment = get_temporal_alignment_table()

        with open(index_file, "r") as f:
            index = json.load(f)
        self.samples = index[split]

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        """Sample N sources, mix, and return."""
        source_indices = random.sample(range(len(self.samples)), self.n_sources)
        sources = [self.samples[i] for i in source_indices]

        # Load waveforms
        audio_waveforms = []
        video_batches = []
        for source in sources:
            wave, frames = self._load_source(source)
            audio_waveforms.append(wave)
            if self.include_visual and frames is not None:
                video_batches.append(frames)

        # Mix
        mixture_wave, source_gains = self._mix_sources(audio_waveforms)
        mixture_stft = self.stft(mixture_wave)
        source_stfts = torch.stack([self.stft(w) for w in audio_waveforms])

        out = {
            "mixture_stft": mixture_stft,
            "source_stfts": source_stfts,
            "n_sources": self.n_sources,
        }
        if video_batches:
            out["source_videos"] = torch.stack(video_batches)
        out["source_gains"] = source_gains
        return out

    def _load_source(self, source: dict) -> Tuple[torch.Tensor, Optional[torch.Tensor]]:
        audio_path = source.get("audio_path", source.get("wav_path"))
        if audio_path and audio_path.endswith('.pt'):
            import torch
            wave = torch.load(audio_path, weights_only=False)
        else:
            import torchaudio
            wave, sr = torchaudio.load(audio_path) if audio_path else (torch.zeros(1, 96000), 16000)
            ap = AudioPreprocessor()
            wave = ap(wave, sr)
        if wave.dim() == 2:
            wave = wave.squeeze(0)

        video_path = source.get("video_path", source.get("frames_path"))
        if self.include_visual and video_path and os.path.exists(video_path):
            frames = torch.load(video_path, weights_only=False)
        else:
            frames = None
        return wave, frames

    def _mix_sources(self, waveforms_chunks: List[torch.Tensor],
                     db_range_spectrogram: Tuple[float, float] = (-5.0, 5.0)
                     ) -> Tuple[torch.Tensor, torch.Tensor]:
        max_len = max(w.shape[-1] for w in waveforms_chunks)
        pad_fn = F.pad
        padded = []
        for w in waveforms_chunks:
            if w.shape[-1] < max_len:
                w = pad_fn(w, (0, max_len - w.shape[-1]))
            padded.append(w)
        stacked = torch.stack(padded)  # [N, L]
        n = stacked.shape[0]
        db = torch.rand(n) * (db_range_spectrogram[1] - db_range_spectrogram[0]) + db_range_spectrogram[0]
        gains = 10 ** (db / 20.0)
        mixture = (stacked * gains.unsqueeze(1)).sum(dim=0)  # [L]
        return mixture, gains


import warnings


class LegacyAudioVisualDataModule:
    """Lightning-style DataModule (DEPRECATED).

    Use src.data.datamodule.AudioVisualDataModule instead.
    """

    def __init__(self, index_file: str, train_config: dict,
                 batch_size: int = 8, num_workers: int = 4):
        warnings.warn(
            "LegacyAudioVisualDataModule is deprecated. "
            "Use src.data.datamodule.AudioVisualDataModule instead.",
            DeprecationWarning, stacklevel=2)
        self.index_file = index_file
        self.batch_size = batch_size
        self.num_workers = num_workers
        self.n_sources = train_config.get("n_sources", 2)
        self.include_visual = train_config.get("include_visual", True)

    def train_dataloader(self) -> DataLoader:
        ds = AudioVisualDataset(
            self.index_file, n_sources=self.n_sources,
            split="train", include_visual=self.include_visual,
        )
        return DataLoader(ds, batch_size=self.batch_size,
                          shuffle=True, num_workers=self.num_workers,
                          pin_memory=True)

    def val_dataloader(self) -> DataLoader:
        ds = AudioVisualDataset(
            self.index_file, n_sources=self.n_sources,
            split="val", include_visual=self.include_visual,
        )
        return DataLoader(ds, batch_size=self.batch_size,
                          shuffle=False, num_workers=self.num_workers,
                          pin_memory=True)

    def test_dataloader(self) -> DataLoader:
        ds = AudioVisualDataset(
            self.index_file, n_sources=self.n_sources,
            split="test", include_visual=self.include_visual,
        )
        return DataLoader(ds, batch_size=self.batch_size,
                          shuffle=False, num_workers=self.num_workers,
                          pin_memory=True)
